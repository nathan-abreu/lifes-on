-- Tabela de usuarios (cadastro/login - Semana 2).
-- A senha nunca e guardada em texto puro, apenas o hash gerado pelo werkzeug.
-- O Flask consulta esta tabela com a chave configurada no ambiente.
create table if not exists usuarios (
    id_usuario bigint generated by default as identity primary key,
    nome text not null,
    email text not null unique,
    senha_hash text not null,
    criado_em timestamptz not null default now()
);

-- Definições para instalação nova; não recriam tabelas existentes.
create table if not exists public.atividades (
    id_atividade bigint generated by default as identity primary key,
    id_usuario bigint not null references public.usuarios(id_usuario),
    tipo_exercicio text not null,
    duracao integer not null check (duracao > 0),
    frequencia integer not null check (frequencia between 1 and 7),
    data_registro timestamptz not null default now()
);

create table if not exists public.metas (
    id_meta bigint generated by default as identity primary key,
    id_usuario bigint not null references public.usuarios(id_usuario),
    descricao text not null,
    prazo date not null,
    progresso integer not null default 0 check (progresso between 0 and 100)
);

create table if not exists public.agenda (
    id_agenda bigint generated by default as identity primary key,
    id_usuario bigint not null references public.usuarios(id_usuario),
    horario timestamp without time zone not null,
    lembrete text
);

create table if not exists public.conquistas (
    id_conquista bigint generated by default as identity primary key,
    nome text not null,
    descricao text not null,
    pontos integer not null default 0
);

create table if not exists public.usuario_conquista (
    id_usuario bigint not null references public.usuarios(id_usuario),
    id_conquista bigint not null references public.conquistas(id_conquista),
    data_obtencao date not null default (now() at time zone 'America/Sao_Paulo')::date,
    primary key (id_usuario, id_conquista)
);

